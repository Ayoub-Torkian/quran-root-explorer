"""Structural audit of the Deep-Dive bundles — run before publishing reports.

Mirrors audit_app.py's discipline (FINDINGS_LEDGER §0c: periodic AUDIT, not
tweaks) but for the deep-dive output tree. For every bundle under
SpatialAnalysis/deep-dives/{concepts,ayahs}/* it checks the required structure
(00_request.json, MANIFEST.json, findings/, data/) and a well-formed MANIFEST
with a verification block, then rewrites deep-dives/_index.md as the registry.

Run:  python audit_deepdives.py     (exit 1 on hard structural drift)
"""
import json
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent / "SpatialAnalysis" / "deep-dives"
REQUIRED = ["00_request.json", "MANIFEST.json"]
REQUIRED_DIRS = ["findings", "data"]


def audit_bundle(d):
    problems = []
    for f in REQUIRED:
        if not (d / f).exists():
            problems.append(f"missing {f}")
    for sub in REQUIRED_DIRS:
        if not (d / sub).is_dir() or not any((d / sub).glob("*.json")):
            problems.append(f"missing/empty {sub}/")
    man = {}
    if (d / "MANIFEST.json").exists():
        try:
            man = json.loads((d / "MANIFEST.json").read_text(encoding="utf-8"))
        except Exception as e:
            problems.append(f"unreadable MANIFEST ({e})")
        if "verification" not in man:
            problems.append("MANIFEST has no verification block")
    return problems, man


def main():
    if not BASE.exists():
        print(f"no deep-dives tree yet at {BASE}")
        sys.exit(0)
    rows = []
    hard = []
    for kind in ("concepts", "ayahs"):
        kd = BASE / kind
        if not kd.is_dir():
            continue
        for d in sorted(p for p in kd.iterdir() if p.is_dir()):
            problems, man = audit_bundle(d)
            status = "OK" if not problems else "DRIFT"
            rep = "✔" if man.get("verification", {}).get("reports_generated") else "·"
            rows.append((kind, d.name, status, rep, man, problems))
            if problems:
                hard.append((d.name, problems))

    # rewrite the registry
    lines = ["# Deep-Dive registry  (auto-generated by audit_deepdives.py)", ""]
    lines.append(f"Bundles: {len(rows)}  ·  structural drift: "
                 f"{'none' if not hard else len(hard)}")
    lines.append("")
    lines.append("| kind | bundle | structure | reports | verification |")
    lines.append("|------|--------|-----------|---------|--------------|")
    for kind, name, status, rep, man, problems in rows:
        v = man.get("verification", {})
        vsum = ", ".join(f"{k}={v[k]}" for k in list(v)[:4]) if v else "—"
        lines.append(f"| {kind} | {name} | {status} | {rep} | {vsum} |")
    if hard:
        lines += ["", "## Structural DRIFT (fix before publishing):"]
        for name, problems in hard:
            lines.append(f"- **{name}**: {'; '.join(problems)}")
    BASE.mkdir(parents=True, exist_ok=True)
    (BASE / "_index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"{'kind':9} {'bundle':28} {'struct':7} reports")
    print("-" * 56)
    for kind, name, status, rep, man, problems in rows:
        print(f"{kind:9} {name:28} {status:7} {rep}")
        for p in problems:
            print(f"    ✘ {p}")
    print()
    if hard:
        print(f"HARD STRUCTURAL DRIFT in {len(hard)} bundle(s) — see _index.md.")
    else:
        print(f"HARD STRUCTURAL DRIFT: none. Wrote {BASE / '_index.md'}.")
    sys.exit(1 if hard else 0)


if __name__ == "__main__":
    main()
